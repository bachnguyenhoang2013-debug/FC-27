/**
 * Picks 3 deterministic random Ginga Festival quests for each 06:00 AM daily cycle.
 */
export function getDailyGingaQuests(cycleKey: string): GingaDailyQuestTemplate[] {
  let hash = 2166136261;
  for (let i = 0; i < cycleKey.length; i++) {
    hash ^= cycleKey.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  const indices: number[] = [];
  const poolSize = GINGA_DAILY_QUEST_POOL.length;
  let seed = Math.abs(hash) >>> 0;
  // Always include check-in or match quest + 2 deterministic picks
  while (indices.length < 3 && indices.length < poolSize) {
    seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
    const idx = seed % poolSize;
    if (!indices.includes(idx)) {
      indices.push(idx);
    }
  }
  return indices.map((idx) => GINGA_DAILY_QUEST_POOL[idx]);
}
