function shuffleArray<T>(list: T[]): T[] {
  const arr = [...list];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

export function pickRandomVietnamQuestions(
  count: number = VIETNAM_QUIZ_QUESTIONS_PER_DAY
): VietnamQuizQuestion[] {
  const picked = shuffleArray(RAW_VIETNAM_QUIZ_BANK).slice(0, count);
  return picked.map((q) => {
    const indexed = q.options.map((text, idx) => ({
      text,
      isCorrect: idx === q.correctIndex,
    }));
    const shuffled = shuffleArray(indexed);
    const nextCorrect = shuffled.findIndex((o) => o.isCorrect);
    return {
      id: q.id,
      question: q.question,
      options: shuffled.map((o) => o.text) as [string, string, string, string],
      correctIndex: nextCorrect >= 0 ? nextCorrect : 0,
    };
  });
}
